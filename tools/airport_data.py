"""Landmark data for the 30 airports (local coords 600x400, ground y=360).
Each entry: code, name, chapter, main paths (landmark body), aux paths (accent colour), plane (x, y, angle)."""
import math


def f(v):
    s = '%.1f' % v
    return s[:-2] if s.endswith('.0') else s


def circle(cx, cy, r):
    return f'M{f(cx - r)} {f(cy)} a{f(r)} {f(r)} 0 1 0 {f(2 * r)} 0 a{f(r)} {f(r)} 0 1 0 {f(-2 * r)} 0'


def ellipse(cx, cy, rx, ry):
    return f'M{f(cx - rx)} {f(cy)} a{f(rx)} {f(ry)} 0 1 0 {f(2 * rx)} 0 a{f(rx)} {f(ry)} 0 1 0 {f(-2 * rx)} 0'


def sample(fn, x0, x1, n=40):
    pts = [(x0 + (x1 - x0) * i / n) for i in range(n + 1)]
    return 'M' + ' L'.join(f'{f(x)} {f(fn(x))}' for x in pts)


def wave(x0, x1, y, amp, period):
    return sample(lambda x: y + amp * math.sin((x - x0) / period * 2 * math.pi), x0, x1, max(12, int((x1 - x0) / 6)))


def palm(x, base, h, lean):
    """returns (trunk, fronds) path strings"""
    tx, ty = x + lean, base - h
    trunk = f'M{f(x)} {f(base)} Q{f(x + lean * .1)} {f(base - h * .6)} {f(tx)} {f(ty)}'
    L = h * .42
    fr = []
    for a in (15, 55, 95, 135, 175):
        ca, sa = math.cos(math.radians(a)), math.sin(math.radians(a))
        ex, ey = tx + L * ca, ty - L * sa * .55 + L * .45
        cx, cy = tx + L * .6 * ca, ty - L * sa * .95 - L * .1
        fr.append(f'M{f(tx)} {f(ty)} Q{f(cx)} {f(cy)} {f(ex)} {f(ey)}')
    return trunk, ' '.join(fr)


def starfish(cx, cy, R, rv, rot):
    pts = []
    for i in range(6):
        a = math.radians(rot + 60 * i)
        pts.append((cx + R * math.cos(a), cy + R * math.sin(a), a))
    d = ''
    for i, (tx, ty, a) in enumerate(pts):
        av = a - math.radians(30)
        vx, vy = cx + rv * math.cos(av), cy + rv * math.sin(av)
        c1 = (cx + R * .62 * math.cos(a - math.radians(20)), cy + R * .62 * math.sin(a - math.radians(20)))
        if i == 0:
            d += f'M{f(vx)} {f(vy)} '
        d += f'Q{f(c1[0])} {f(c1[1])} {f(tx)} {f(ty)} '
        av2 = a + math.radians(30)
        vx2, vy2 = cx + rv * math.cos(av2), cy + rv * math.sin(av2)
        c2 = (cx + R * .62 * math.cos(a + math.radians(20)), cy + R * .62 * math.sin(a + math.radians(20)))
        d += f'Q{f(c2[0])} {f(c2[1])} {f(vx2)} {f(vy2)} '
    return d + 'Z'


def spokes(cx, cy, r0, r1, rot):
    d = []
    for i in range(6):
        a = math.radians(rot + 60 * i)
        d.append(f'M{f(cx + r0 * math.cos(a))} {f(cy + r0 * math.sin(a))} L{f(cx + r1 * math.cos(a))} {f(cy + r1 * math.sin(a))}')
    return ' '.join(d)


def sail(x0, w, h, base=300):
    ax = x0 + .62 * w
    return (f'M{f(x0)} {base} Q{f(x0 + .02 * w)} {f(base - h * .85)} {f(ax)} {f(base - h)} '
            f'Q{f(x0 + w * .9)} {f(base - h * .55)} {f(x0 + w)} {base} Z')


def quad_pt(p0, p1, p2, t):
    return ((1 - t) ** 2 * p0[0] + 2 * (1 - t) * t * p1[0] + t * t * p2[0],
            (1 - t) ** 2 * p0[1] + 2 * (1 - t) * t * p1[1] + t * t * p2[1])


def arches(centers, base, w, h):
    r = w / 2
    return ' '.join(f'M{f(c - r)} {f(base)} V{f(base - h)} A{f(r)} {f(r)} 0 0 1 {f(c + r)} {f(base - h)} V{f(base)}' for c in centers)


